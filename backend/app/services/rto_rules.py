"""
Нормативы режима труда и отдыха водителей.

Источник: Приказ Минтранса России от 14.04.2026 № 160 "Об установлении
особенностей режима рабочего времени и времени отдыха водителей
автомобилей" (зарегистрирован в Минюсте России 15.05.2026 № 86476),
действует с 01.09.2026.

Значения ниже сверены с официальным текстом приказа:
  - управление за 24 часа: базовое 9 ч, с увеличением на 1 ч (до 10 ч)
    не более 2 раз в неделю;
  - не позднее 4 ч 30 мин управления — перерыв не менее 45 мин;
  - ежедневный отдых: базовый не менее 11 ч, сокращённый до 9 ч
    (не более 3 раз между двумя еженедельными отдыхами);
  - еженедельный отдых: не менее 45 ч, до начала 7-го рабочего дня;
  - управление за 2 последовательные календарные недели: не более 90 ч.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class RtoRules:
    # Максимальное время управления в течение суток, часы
    max_daily_driving_hours: float = 9.0
    # Разрешено до двух раз в неделю увеличивать до, часы
    max_daily_driving_hours_extended: float = 10.0
    max_extended_days_per_week: int = 2

    # Максимальное непрерывное время за рулём без перерыва, часы
    max_continuous_driving_hours: float = 4.5
    # Минимальный перерыв после непрерывного вождения, минуты
    min_break_after_continuous_minutes: int = 45

    # Минимальный ежедневный отдых, часы
    min_daily_rest_hours: float = 11.0
    # Сокращённый ежедневный отдых (с компенсацией), часы
    min_daily_rest_hours_reduced: float = 9.0

    # Минимальный еженедельный отдых, часы
    min_weekly_rest_hours: float = 45.0

    # Максимальное суммарное время управления за две недели подряд, часы
    max_biweekly_driving_hours: float = 90.0


DEFAULT_RULES = RtoRules()
